import {mkdir,writeFile} from 'node:fs/promises';
const codes={RO:11,AC:12,AM:13,RR:14,PA:15,AP:16,TO:17,MA:21,PI:22,CE:23,RN:24,PB:25,PE:26,AL:27,SE:28,BA:29,MG:31,ES:32,RJ:33,SP:35,PR:41,SC:42,RS:43,MS:50,MT:51,GO:52,DF:53};
const baseline={fetchedAt:new Date().toISOString(),election:'6257',states:{}};
const {normalize}=await import('../src/lib/model.js');
const keys=[...Object.keys(codes),'ZZ'];
for(let i=0;i<keys.length;i+=4) await Promise.all(keys.slice(i,i+4).map(async uf=>{const u=uf.toLowerCase();const url=`https://resultados.tse.jus.br/oficial/ele2026/6257/dados/${u}/${u}-c0001-e006257-u.json`;const r=await fetch(url);if(!r.ok)throw Error(`${uf}: ${r.status}`);baseline.states[uf]={...normalize(await r.json()),source:url};}));
await mkdir('data',{recursive:true});
await writeFile('data/reference.json',JSON.stringify(baseline));
const response=await fetch('https://servicodados.ibge.gov.br/api/v3/malhas/paises/BR?formato=application/vnd.geo%2Bjson&qualidade=minima&intrarregiao=UF');
if(!response.ok)throw Error('Mapa indisponível');
const geo=await response.json();
const points=c=>typeof c[0]==='number'?[c]:c.flatMap(points);
const all=geo.features.flatMap(f=>points(f.geometry.coordinates));
const minx=Math.min(...all.map(p=>p[0])),maxx=Math.max(...all.map(p=>p[0])),miny=Math.min(...all.map(p=>p[1])),maxy=Math.max(...all.map(p=>p[1]));
const project=p=>[(p[0]-minx)/(maxx-minx)*490+15,(maxy-p[1])/(maxy-miny)*480+10];
const ring=c=>c.map((p,i)=>(i?'L':'M')+project(p).map(n=>n.toFixed(1)).join(',')).join('')+'Z';
const map=geo.features.map(f=>({uf:Object.keys(codes).find(k=>String(codes[k])===String(f.properties.codarea)),d:(f.geometry.type==='Polygon'?[f.geometry.coordinates]:f.geometry.coordinates).map(poly=>poly.map(ring).join('')).join('')}));
await writeFile('public/map.json',JSON.stringify(map));
console.log(`Referência oficial: ${keys.length} abrangências; mapa IBGE: ${map.length} UFs.`);
